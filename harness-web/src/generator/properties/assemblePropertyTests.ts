/**
 * Property-test assembler: fuzz tests and a stateful invariant suite.
 *
 * The attack suite is a regression suite for the mitigations — it fails when one
 * is removed. This suite is for what the user ADDS. Every property here holds for
 * the generated contract and must keep holding for any strategy, hook or feature
 * layered on top of it, and Foundry drives it with random inputs and random
 * action sequences rather than the fixed values a hand-written test would pick.
 *
 * Each preset gets:
 *   - fuzz tests: `testFuzz_*`, one property per test, inputs bounded to what the
 *     live market at the pinned block can serve;
 *   - a handler contract that performs only valid actions, and invariants checked
 *     after every action sequence. `fail_on_revert = true` in the exported
 *     foundry.toml, so a revert inside a valid action is itself a failure.
 */

export interface PropertyTest {
  name: string;
  /** One line: what this proves about the user's contract. */
  claim: string;
  kind: 'fuzz' | 'invariant';
}

export function assemblePropertyTests(opts: GenerateOptions): {
  source: string;
  tests: PropertyTest[];
} {
  if (!CONTRACT_NAME_RE.test(opts.name)) {
    throw new Error(`Refusing to interpolate an invalid contract name: ${opts.name}`);
  }
  const { contract } = buildPreset(opts);
  const scaffold = scaffoldFor(opts);
  const ctorArgs = contract.constructorArgs.map((a) => {
    const bound = scaffold.bindings[a.name];
    if (!bound) throw new Error(`No test binding for constructor argument '${a.name}'`);
    return bound;
  });

  const body = bodyFor(opts, scaffold);

  const lines: string[] = [
    '// SPDX-License-Identifier: MIT',
    `pragma solidity ${SOLIDITY_PRAGMA};`,
    '',
    `import {Test} from "${IMPORT_PATHS.FORGE_TEST}";`,
    ...(scaffold.aave
      ? [
          `import {IPool} from "${IMPORT_PATHS.POOL}";`,
          `import {IPoolAddressesProvider} from "${IMPORT_PATHS.POOL_ADDRESSES_PROVIDER}";`,
        ]
      : []),
    `import {IERC20} from "${IMPORT_PATHS.IERC20}";`,
    ...scaffold.imports,
    ...body.imports,
    `import {${opts.name}} from "../src/${opts.name}.sol";`,
    '',
    ...body.handler,
    '',
    `/// @title ${opts.name}PropertiesTest`,
    '/// @notice Generated by HARNESS. Properties that hold for this contract and must',
    '/// @notice keep holding for anything you build on it. Foundry fuzzes the inputs',
    '/// @notice and the action sequences; the values are not hand-picked. Runs on a',
    '/// @notice mainnet fork against the real protocol.',
    `contract ${opts.name}PropertiesTest is Test {`,
    ...(scaffold.aave
      ? [
          '    IPoolAddressesProvider internal constant PROVIDER =',
          `        IPoolAddressesProvider(${AAVE_MAINNET.POOL_ADDRESSES_PROVIDER});`,
        ]
      : []),
    ...scaffold.constants.map((l) => `    ${l}`),
  ];
  if (opts.claimRewards && scaffold.aave) {
    lines.push(`    address internal constant REWARDS_CONTROLLER = ${AAVE_MAINNET.REWARDS_CONTROLLER};`);
  }
  lines.push(
    '',
    ...scaffold.state.map((l) => `    ${l}`),
    ...body.state.map((l) => `    ${l}`),
    '',
    '    function setUp() public {',
    ...forkSetUpLines().map((l) => `        ${l}`),
    '',
    ...scaffold.setUp.map((l) => `        ${l}`),
    `        harness = new ${opts.name}(${ctorArgs.join(', ')});`,
    ...(scaffold.afterDeploy ?? []).map((l) => `        ${l}`),
    ...body.setUp.map((l) => `        ${l}`),
    '    }',
    '',
    ...scaffold.helpers.map((l) => (l === '' ? '' : `    ${l}`)),
    '',
    ...body.tests.map((l) => (l === '' ? '' : `    ${l}`)),
    '}',
    '',
  );

  const source = lines.join('\n');
  const leftover = source.match(/\{\{[A-Z_]+\}\}/g);
  if (leftover) {
    throw new Error(`Unsubstituted placeholder(s) in property tests: ${[...new Set(leftover)].join(', ')}`);
  }
  return { source, tests: body.catalogue };
}

interface Body {
  imports: string[];
  handler: string[];
  state: string[];
  setUp: string[];
  tests: string[];
  catalogue: PropertyTest[];
}

function bodyFor(opts: GenerateOptions, scaffold: Scaffold): Body {
  switch (opts.preset) {
    case 'aave-v3-erc4626-vault':
      return vaultBody(opts, {
        position: 'IERC20(ATOKEN).balanceOf(address(vault))',
        positionTest: 'IERC20(ATOKEN).balanceOf(address(harness))',
        donate: [
          '// Real aTokens, then a plain transfer: no Aave call touches the vault.',
          'deal(ASSET, address(this), amount);',
          'IERC20(ASSET).approve(address(POOL), amount);',
          'POOL.supply(ASSET, amount, address(this), 0);',
          'IERC20(ATOKEN).transfer(address(vault), IERC20(ATOKEN).balanceOf(address(this)));',
        ],
        donateTest: [
          'deal(ASSET, whale, amount);',
          'vm.startPrank(whale);',
          'IERC20(ASSET).approve(address(POOL), amount);',
          'POOL.supply(ASSET, amount, whale, 0);',
          'IERC20(ATOKEN).transfer(address(harness), IERC20(ATOKEN).balanceOf(whale));',
          'vm.stopPrank();',
        ],
        handlerCtorExtra: ['IPool internal POOL;', 'address internal ATOKEN;', 'address internal ASSET;'],
        handlerCtorArgs: 'IPool pool_, address atoken_, address asset_',
        handlerCtorBody: ['POOL = pool_;', 'ATOKEN = atoken_;', 'ASSET = asset_;'],
        handlerNew: 'POOL, ATOKEN, ASSET',
        scaffold,
      });
    case 'morpho-blue-vault':
      return vaultBody(opts, {
        position:
          'MorphoBalancesLib.expectedSupplyAssets(IMorpho(MORPHO), vault.marketParams(), address(vault))',
        positionTest:
          'MorphoBalancesLib.expectedSupplyAssets(IMorpho(MORPHO), harness.marketParams(), address(harness))',
        donate: [
          '// Morpho lets anyone supply on behalf of any address: a donation with no vault call.',
          'deal(ASSET, address(this), amount);',
          'IERC20(ASSET).approve(MORPHO, amount);',
          'IMorpho(MORPHO).supply(vault.marketParams(), amount, 0, address(vault), "");',
        ],
        donateTest: [
          'deal(ASSET, whale, amount);',
          'vm.startPrank(whale);',
          'IERC20(ASSET).approve(MORPHO, amount);',
          'IMorpho(MORPHO).supply(harness.marketParams(), amount, 0, address(harness), "");',
          'vm.stopPrank();',
        ],
        extraImports: [
          `import {MorphoBalancesLib} from "${IMPORT_PATHS.MORPHO_BALANCES_LIB}";`,
        ],
        handlerCtorExtra: ['address internal MORPHO;', 'address internal ASSET;'],
        handlerCtorArgs: 'address morpho_, address asset_',
        handlerCtorBody: ['MORPHO = morpho_;', 'ASSET = asset_;'],
        handlerNew: 'MORPHO, ASSET',
        scaffold,
      });
    case 'compound-v3-vault':
      return vaultBody(opts, {
        position: 'ICometTest(COMET).balanceOf(address(vault))',
        positionTest: 'ICometTest(COMET).balanceOf(address(harness))',
        donate: [
          '// Comet lets anyone supply to any account: a donation with no vault call.',
          'deal(ASSET, address(this), amount);',
          'IERC20(ASSET).approve(COMET, amount);',
          'ICometTest(COMET).supplyTo(address(vault), ASSET, amount);',
        ],
        donateTest: [
          'deal(ASSET, whale, amount);',
          'vm.startPrank(whale);',
          'IERC20(ASSET).approve(COMET, amount);',
          'ICometTest(COMET).supplyTo(address(harness), ASSET, amount);',
          'vm.stopPrank();',
        ],
        handlerCtorExtra: ['address internal COMET;', 'address internal ASSET;'],
        handlerCtorArgs: 'address comet_, address asset_',
        handlerCtorBody: ['COMET = comet_;', 'ASSET = asset_;'],
        handlerNew: 'COMET, ASSET',
        scaffold,
      });
    case 'aave-v3-flashloan-receiver':
      return flashLoanBody(opts);
    case 'token-sale-launchpad':
      return saleBody(opts);
    case 'bonding-curve-launchpad':
      return curveBody(opts);
  }
}

