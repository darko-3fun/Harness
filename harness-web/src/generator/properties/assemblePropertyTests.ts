interface VaultParts {
  /** Expression for the vault's real position in the market, from inside the handler. */
  position: string;
  /** The same, from inside the test contract. */
  positionTest: string;
  /** Lines that donate `amount` of the asset into the vault's market position, from the handler. */
  donate: string[];
  /** The same from the test contract, acting as `whale`. */
  donateTest: string[];
  extraImports?: string[];
  handlerCtorExtra: string[];
  handlerCtorArgs: string;
  handlerCtorBody: string[];
  handlerNew: string;
  scaffold: Scaffold;
}

function vaultBody(opts: GenerateOptions, p: VaultParts): Body {
  const N = opts.name;
  const offset = opts.decimalsOffset ?? 6;
  const handler = [
    '/// @dev Drives the vault with bounded, valid actions from a small cast of actors. Every',
    '/// @dev action is either valid by construction or skipped, so a revert is a real finding.',
    `contract ${N}Handler is Test {`,
    ...FRESH_HELPER(N).map((l) => `    ${l}`),
    '',
    `    ${N} internal vault;`,
    '    address internal harvester;',
    '    uint256 internal unit;',
    ...p.handlerCtorExtra.map((l) => `    ${l}`),
    '    address[] internal actors;',
    '',
    '    uint256 public ghostDeposited;',
    '    uint256 public ghostWithdrawn;',
    '    uint256 public ghostDonated;',
    '',
    `    constructor(${N} vault_, address harvester_, uint256 unit_, ${p.handlerCtorArgs}) {`,
    '        vault = vault_;',
    '        harvester = harvester_;',
    '        unit = unit_;',
    ...p.handlerCtorBody.map((l) => `        ${l}`),
    '        for (uint256 i = 0; i < 3; i++) {',
    '            actors.push(_fresh(string(abi.encodePacked("actor", vm.toString(i)))));',
    '        }',
    '    }',
    '',
    '    function actorCount() external view returns (uint256) {',
    '        return actors.length;',
    '    }',
    '',
    '    function actor(uint256 i) external view returns (address) {',
    '        return actors[i];',
    '    }',
    '',
    '    function _actor(uint256 seed) internal view returns (address) {',
    '        return actors[bound(seed, 0, actors.length - 1)];',
    '    }',
    '',
    '    /// @dev Lending markets reject dust: a supply whose scaled amount rounds to zero',
    '    /// @dev reverts. Everything here stays above a millionth of the reference amount.',
    '    function _dust() internal view returns (uint256) {',
    '        return unit / 1_000_000 + 1;',
    '    }',
    '',
    '    function deposit(uint256 seed, uint256 amount) external {',
    '        address a = _actor(seed);',
    '        uint256 cap = vault.maxDeposit(a);',
    '        if (cap > 50 * unit) cap = 50 * unit;',
    '        if (cap < _dust()) return;',
    '        amount = bound(amount, _dust(), cap);',
    '        if (vault.previewDeposit(amount) == 0) return;',
    '        deal(ASSET, a, amount);',
    '        vm.startPrank(a);',
    '        IERC20(ASSET).approve(address(vault), amount);',
    '        vault.deposit(amount, a);',
    '        vm.stopPrank();',
    '        ghostDeposited += amount;',
    '    }',
    '',
    '    function redeem(uint256 seed, uint256 shares) external {',
    '        address a = _actor(seed);',
    '        uint256 max = vault.maxRedeem(a);',
    '        if (max == 0) return;',
    '        shares = bound(shares, 1, max);',
    '        if (vault.previewRedeem(shares) < _dust()) return;',
    '        vm.prank(a);',
    '        ghostWithdrawn += vault.redeem(shares, a, a);',
    '    }',
    '',
    '    function withdraw(uint256 seed, uint256 assets) external {',
    '        address a = _actor(seed);',
    '        uint256 max = vault.maxWithdraw(a);',
    '        if (max < _dust()) return;',
    '        assets = bound(assets, _dust(), max);',
    '        vm.prank(a);',
    '        vault.withdraw(assets, a, a);',
    '        ghostWithdrawn += assets;',
    '    }',
    '',
    '    function warpAndHarvest(uint256 dt) external {',
    '        vm.warp(block.timestamp + bound(dt, 1 hours, 30 days));',
    '        vm.prank(harvester);',
    '        vault.harvest();',
    '    }',
    '',
    ...(opts.feeBps
      ? [
          '    function collectFees() external {',
          '        vm.prank(harvester);',
          '        vault.collectFees();',
          '    }',
          '',
        ]
      : []),
    '    /// @dev A donation straight into the market position, bypassing the vault entirely.',
    '    function donate(uint256 amount) external {',
    '        amount = bound(amount, unit / 100, 10 * unit);',
    ...p.donate.map((l) => `        ${l}`),
    '        ghostDonated += amount;',
    '    }',
    '',
    '    function position() external view returns (uint256) {',
    `        return ${p.position};`,
    '    }',
    '}',
  ];

  const tests = [
    '// ------------------------------------------------------------------ fuzz',
    '',
    '/// @notice A deposit followed by a full redeem never returns more than it put in,',
    '/// @notice at any size. The rounding is on the vault\'s side of every conversion.',
    'function testFuzz_RoundTripNeverProfits(uint256 amount) public {',
    '    amount = bound(amount, ONE / 1000, 50 * AMOUNT);',
    '    vm.assume(harness.previewDeposit(amount) > 0);',
    '    uint256 shares = _deposit(alice, amount);',
    '    vm.prank(alice);',
    '    uint256 back = harness.redeem(shares, alice, alice);',
    '    assertLe(back, amount, "round trip returned more than it cost");',
    '}',
    '',
    '/// @notice What the vault promises equals what it does: deposit() returns exactly',
    '/// @notice previewDeposit(), redeem() returns exactly previewRedeem().',
    'function testFuzz_PreviewMatchesExecution(uint256 amount) public {',
    '    amount = bound(amount, ONE / 1000, 50 * AMOUNT);',
    '    vm.assume(harness.previewDeposit(amount) > 0);',
    '    uint256 predicted = harness.previewDeposit(amount);',
    '    uint256 shares = _deposit(alice, amount);',
    '    assertEq(shares, predicted, "deposit() disagrees with previewDeposit()");',
    '    uint256 predictedAssets = harness.previewRedeem(shares);',
    '    vm.prank(alice);',
    '    uint256 got = harness.redeem(shares, alice, alice);',
    '    assertEq(got, predictedAssets, "redeem() disagrees with previewRedeem()");',
    '}',
    '',
    '/// @notice A donation into the vault\'s market position, of any size, moves neither',
    '/// @notice totalAssets() nor the share price. AAVE-VLT-003 as a property.',
    'function testFuzz_DonationDoesNotMovePrice(uint256 deposit, uint256 donation) public {',
    '    deposit = bound(deposit, ONE / 100, 20 * AMOUNT);',
    '    donation = bound(donation, ONE / 100, 200 * AMOUNT);',
    '    vm.assume(harness.previewDeposit(deposit) > 0);',
    '    _deposit(alice, deposit);',
    '    uint256 price = harness.convertToAssets(ONE);',
    '    uint256 total = harness.totalAssets();',
    '    address whale = _fresh("whale");',
    '    uint256 amount = donation;',
    ...p.donateTest.map((l) => `    ${l}`),
    '    assertEq(harness.totalAssets(), total, "totalAssets moved on a donation");',
    '    assertEq(harness.convertToAssets(ONE), price, "share price moved on a donation");',
    '}',
    '',
    '/// @notice Harvesting after any amount of time never lowers the share price: the fee',
    '/// @notice is taken from yield only, never from principal.',
    'function testFuzz_HarvestNeverLowersPrice(uint256 amount, uint256 dt) public {',
    '    amount = bound(amount, ONE / 100, 50 * AMOUNT);',
    '    dt = bound(dt, 1 hours, 365 days);',
    '    vm.assume(harness.previewDeposit(amount) > 0);',
    '    _deposit(alice, amount);',
    '    uint256 before = harness.convertToAssets(ONE);',
    '    vm.warp(block.timestamp + dt);',
    '    vm.prank(owner);',
    '    harness.harvest();',
    '    assertGe(harness.convertToAssets(ONE), before, "harvest lowered the share price");',
    `    assertLe(harness.totalAssets(), ${p.positionTest}, "book exceeds the market position after harvest");`,
    '}',
    '',
    '/// @notice The limits are honest: withdrawing exactly maxWithdraw() and redeeming',
    '/// @notice exactly maxRedeem() both succeed.',
    'function testFuzz_MaxLimitsAreHonest(uint256 amount) public {',
    '    amount = bound(amount, ONE / 100, 50 * AMOUNT);',
    '    vm.assume(harness.previewDeposit(amount) > 0);',
    '    _deposit(alice, amount);',
    '    uint256 maxW = harness.maxWithdraw(alice);',
    '    vm.prank(alice);',
    '    harness.withdraw(maxW / 2, alice, alice);',
    '    uint256 maxR = harness.maxRedeem(alice);',
    '    vm.prank(alice);',
    '    harness.redeem(maxR, alice, alice);',
    '    assertEq(harness.balanceOf(alice), 0, "maxRedeem left shares behind");',
    '}',
    '',
    `/// @notice The empty-vault inflation attack is bounded by the virtual-share offset (${offset}):`,
    '/// @notice even when the harvester credits an attacker\'s donation, the next depositor',
    `/// @notice loses at most 1 / 10^${offset} of their deposit to rounding.`,
    'function testFuzz_FirstDepositorLossIsBounded(uint256 victim, uint256 donation) public {',
    '    victim = bound(victim, ONE, 20 * AMOUNT);',
    '    donation = bound(donation, ONE, 100 * AMOUNT);',
    '    // Attacker: the smallest position the market accepts, then a donation credited by harvest.',
    '    _deposit(bob, ONE / 1000);',
    '    address whale = bob;',
    '    uint256 amount = donation;',
    ...p.donateTest.map((l) => `    ${l}`),
    '    vm.prank(owner);',
    '    harness.harvest();',
    '    // Victim deposits. Their loss is at most one share of rounding, and the attacker',
    `    // paid at least 10^${offset} times that loss to cause it (the OpenZeppelin bound).`,
    '    uint256 shares = _deposit(alice, victim);',
    '    uint256 value = harness.convertToAssets(shares);',
    '    uint256 loss = victim > value ? victim - value : 0;',
    '    // One share of vault rounding plus one unit of the market rounding its scaled balance.',
    '    assertLe(loss, harness.convertToAssets(1) + 2, "victim lost more than the rounding allows");',
    `    assertLe(loss * (10 ** ${offset}), donation + (10 ** ${offset}), "the attack cost less than 10^offset times the loss");`,
    '}',
    '',
    '// ------------------------------------------------------------- invariants',
    '',
    '/// @notice The vault never books more than it holds in the market.',
    'function invariant_Solvent() public view {',
    '    assertLe(harness.totalAssets(), handler.position(), "totalAssets exceeds the market position");',
    '}',
    '',
    '/// @notice Every share is backed: redeeming all shares asks for at most totalAssets.',
    'function invariant_SharesBackedByAssets() public view {',
    '    assertLe(harness.convertToAssets(harness.totalSupply()), harness.totalAssets() + 1, "shares claim more than the book");',
    '}',
    '',
    '/// @notice Limits never promise more than the holder\'s shares are worth.',
    'function invariant_LimitsNeverOverpromise() public view {',
    '    for (uint256 i = 0; i < handler.actorCount(); i++) {',
    '        address a = handler.actor(i);',
    '        assertLe(harness.maxRedeem(a), harness.balanceOf(a), "maxRedeem exceeds balance");',
    '        assertLe(harness.maxWithdraw(a), harness.convertToAssets(harness.balanceOf(a)), "maxWithdraw exceeds value");',
    '    }',
    '}',
    '',
    '/// @notice Value is conserved: what left plus what remains never exceeds what came in',
    '/// @notice plus the market\'s own yield (which harvest credits) plus donations.',
    'function invariant_NoValueFromNowhere() public view {',
    '    uint256 inflow = handler.ghostDeposited() + handler.ghostDonated();',
    '    // Interest accrued on the fork is bounded generously: no vault yields 100% a month.',
    '    uint256 yieldBound = inflow / 2 + ONE;',
    '    assertLe(handler.ghostWithdrawn() + harness.totalAssets(), inflow + yieldBound, "more value left than ever entered");',
    '}',
    '',
    '/// @notice After any sequence, every actor can leave in full.',
    'function afterInvariant() public {',
    '    for (uint256 i = 0; i < handler.actorCount(); i++) {',
    '        address a = handler.actor(i);',
    '        uint256 max = harness.maxRedeem(a);',
    '        if (max == 0) continue;',
    '        vm.prank(a);',
    '        harness.redeem(max, a, a);',
    '    }',
    '}',
  ];

  return {
    imports: p.extraImports ?? [],
    handler,
    state: [`${N}Handler internal handler;`],
    setUp: [
      `handler = new ${N}Handler(harness, owner, AMOUNT, ${p.handlerNew});`,
      'targetContract(address(handler));',
      '// One fixed sender: a random sender per call would touch a fresh account (and an',
      '// RPC round trip) on every step, for no extra coverage.',
      'targetSender(_fresh("invariantSender"));',
      `bytes4[] memory selectors = new bytes4[](${opts.feeBps ? 6 : 5});`,
      'selectors[0] = handler.deposit.selector;',
      'selectors[1] = handler.redeem.selector;',
      'selectors[2] = handler.withdraw.selector;',
      'selectors[3] = handler.warpAndHarvest.selector;',
      'selectors[4] = handler.donate.selector;',
      ...(opts.feeBps ? ['selectors[5] = handler.collectFees.selector;'] : []),
      'targetSelector(FuzzSelector({addr: address(handler), selectors: selectors}));',
    ],
    tests,
    catalogue: [
      { name: 'testFuzz_RoundTripNeverProfits', kind: 'fuzz', claim: 'deposit then redeem never returns more than it cost, at any size' },
      { name: 'testFuzz_PreviewMatchesExecution', kind: 'fuzz', claim: 'deposit() and redeem() return exactly what the preview functions promised' },
      { name: 'testFuzz_DonationDoesNotMovePrice', kind: 'fuzz', claim: 'a donation of any size into the market position moves neither totalAssets nor the share price' },
      { name: 'testFuzz_HarvestNeverLowersPrice', kind: 'fuzz', claim: 'harvesting after any interval never lowers the share price and never books more than the market holds' },
      { name: 'testFuzz_MaxLimitsAreHonest', kind: 'fuzz', claim: 'withdrawing maxWithdraw and redeeming maxRedeem both succeed' },
      { name: 'testFuzz_FirstDepositorLossIsBounded', kind: 'fuzz', claim: `the inflation attack costs a depositor at most 1/10^${offset} of their deposit` },
      { name: 'invariant_Solvent', kind: 'invariant', claim: 'the book never exceeds the market position, after any sequence of deposits, withdrawals, harvests and donations' },
      { name: 'invariant_SharesBackedByAssets', kind: 'invariant', claim: 'redeeming every share asks for at most totalAssets' },
      { name: 'invariant_LimitsNeverOverpromise', kind: 'invariant', claim: 'maxWithdraw and maxRedeem never exceed what a holder owns' },
      { name: 'invariant_NoValueFromNowhere', kind: 'invariant', claim: 'value out plus value held never exceeds value in plus yield and donations' },
    ],
  };
}

