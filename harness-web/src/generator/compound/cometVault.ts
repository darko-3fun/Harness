/**
 * ERC-4626 vault over a Compound v3 Comet.
 *
 * Comet is not Aave with a different address. Three things are different enough
 * to carry their own finding:
 *
 *   CMPD-VLT-019  `withdraw(base, amount)` has no "amount <= balance" check. If
 *                 the account holds collateral, an over-withdraw SILENTLY OPENS A
 *                 BORROW — and `supplyTo(vault, collateral, x)` is permissionless,
 *                 so anyone can hand the vault collateral. Every withdraw here is
 *                 capped at the supplied balance, and the position is asserted
 *                 non-negative afterwards.
 *   CMPD-VLT-020  balances are present values that round DOWN on every supply and
 *                 withdraw, by up to a base unit. The vault books what the position
 *                 actually moved by, never the amount it asked for.
 *   CMPD-VLT-021  COMP accrues to the Comet account — the vault — and can only be
 *                 claimed to a third party by the account itself (`claimTo` checks
 *                 `hasPermission(src, msg.sender)`). Without a claim path the
 *                 rewards are stranded forever.
 *
 * Comet ships no importable interface at a compatible pragma (its files are
 * `pragma solidity 0.8.15`, exact), so a minimal one is declared in this file.
 */

const COMET_INTERFACE = `/// @dev The slice of Compound v3's Comet this vault uses. Comet is \`pragma solidity 0.8.15\`
/// @dev exactly and is not published to npm, so the interface is declared here.
interface IComet {
    function supply(address asset, uint256 amount) external;
    function withdraw(address asset, uint256 amount) external;
    function withdrawTo(address to, address asset, uint256 amount) external;
    function accrueAccount(address account) external;
    function balanceOf(address account) external view returns (uint256);
    function borrowBalanceOf(address account) external view returns (uint256);
    function baseToken() external view returns (address);
    function isSupplyPaused() external view returns (bool);
    function isWithdrawPaused() external view returns (bool);
}

/// @dev CometRewards, shared by every Comet on a chain.
interface ICometRewards {
    function claimTo(address comet, address src, address to, bool shouldAccrue) external;
}`;

function validate(opts: GenerateOptions): void {
  const messages: ValidationMessages = {};
  validateCommon(opts, messages);
  validateVaultSettings(opts, messages);
  if (!messages.asset && !cometFor(opts.asset)) {
    messages.asset = 'No Compound v3 Comet lends this asset on Ethereum. Pick USDC, WETH or USDT.';
  }
  throwIfInvalid(messages);
}

export function buildCometVault(opts: GenerateOptions): {
  contract: ContractBuilder;
  appliedFindingIds: FindingId[];
} {
  validate(opts);

  const applied: FindingId[] = [];
  const c = new ContractBuilder(opts.name);
  c.license = 'MIT';

  c.addParent(imp('ERC4626', IMPORT_PATHS.ERC4626), [{ lit: 'asset_' }]);
  c.addConstructionOnly(imp('ERC20', IMPORT_PATHS.ERC20), [
    { lit: `"${opts.name}"` },
    { lit: `"c${opts.name.slice(0, 10).toUpperCase()}"` },
  ]);
  c.addImportOnly(imp('IERC20', IMPORT_PATHS.IERC20));

  c.addLibrary(imp('SafeERC20', IMPORT_PATHS.SAFE_ERC20), ['IERC20']);
  applied.push(FINDING_IDS.UNCHECKED_EXTERNAL_CALL);

  c.addNatspecTag('title', opts.name);
  c.addNatspecTag(
    'notice',
    'ERC-4626 vault over Compound v3 generated by HARNESS. Withdrawals are capped at the supplied balance so the position can never go negative, and the share price comes from internal accounting.',
  );

  addCometConstructor(c, opts, applied);
  addCometAccounting(c, opts, applied);
  addCometDepositWithdraw(c, opts, applied);
  addCometLimits(c, opts, applied);
  addCometHarvest(c, opts);
  addCometSurface(c, opts, applied);

  return { contract: c, appliedFindingIds: applied };
}

export function printCometVault(opts: GenerateOptions): string {
  const { contract } = buildCometVault(opts);
  return withPreamble(print(contract), COMET_INTERFACE);
}

