function addCometConstructor(c: ContractBuilder, opts: GenerateOptions, applied: FindingId[]): void {
  c.addConstructorArgument({ type: 'address', name: 'comet_' });
  c.addConstructorArgument({ type: 'IERC20', name: 'asset_' });

  c.addConstantOrImmutableOrErrorDefinition('IComet public immutable COMET;');
  c.addConstantOrImmutableOrErrorDefinition('error AssetIsNotCometBase(address asset, address base);');

  c.addConstructorCode('COMET = IComet(comet_);');
  c.addConstructorCode(
    '// CMPD-VLT-019 — Comet.supply() moves BOTH base and collateral through the same',
    // continues below
  );
  c.addConstructorCode('// signature. A vault whose asset is one of the Comet\'s collaterals would book');
  c.addConstructorCode('// collateral it can never withdraw as base. Refuse anything but the base token.');
  c.addConstructorCode('address base = COMET.baseToken();');
  c.addConstructorCode('if (address(asset_) != base) revert AssetIsNotCometBase(address(asset_), base);');
  applied.push(FINDING_IDS.COMET_WITHDRAW_OPENS_BORROW);

  setAccessControl(c, accessOf(opts));
}

/** AAVE-VLT-003 carries over: `supplyTo(vault, base, x)` is a donation anyone can make. */
function addCometAccounting(c: ContractBuilder, opts: GenerateOptions, applied: FindingId[]): void {
  c.addStateVariable('uint256 private _managedAssets;', false);

  const fns = defineFunctions({
    totalAssets: { kind: 'public', args: [], returns: ['uint256'], mutability: 'view' },
    _decimalsOffset: { kind: 'internal', args: [], returns: ['uint8'], mutability: 'pure' },
  });

  c.setFunctionComments(
    [
      '/// @notice Assets under management, tracked internally.',
      '/// @dev AAVE-VLT-003 — deliberately NOT COMET.balanceOf(address(this)). Comet\'s',
      '/// @dev supplyTo() lets anyone add to this vault\'s position without touching the',
      '/// @dev vault, which is a free share-price move if the balance were the denominator.',
    ],
    fns.totalAssets,
  );
  c.setFunctionBody(['return _managedAssets;'], fns.totalAssets);
  c.addOverride({ name: 'ERC4626' }, fns.totalAssets);

  const offset = opts.decimalsOffset ?? 6;
  c.setFunctionComments(
    [
      '/// @dev AAVE-VLT-003 — virtual shares, so an empty vault cannot be inflated.',
      `/// @dev At offset ${offset}, seeding the rounding attack costs roughly 10^${offset}`,
      '/// @dev times the deposit the attacker is trying to capture.',
    ],
    fns._decimalsOffset,
  );
  c.setFunctionBody([`return ${offset};`], fns._decimalsOffset);
  c.addOverride({ name: 'ERC4626' }, fns._decimalsOffset);

  applied.push(FINDING_IDS.VAULT_ATOKEN_BALANCE_DENOMINATOR);
  applied.push(FINDING_IDS.VAULT_RECEIVER_OWNER_CONFLATED);

  if (opts.depositCap !== undefined) {
    c.addConstantOrImmutableOrErrorDefinition(
      `uint256 public constant DEPOSIT_CAP = ${opts.depositCap};`,
    );
    c.addConstantOrImmutableOrErrorDefinition(
      'error DepositCapExceeded(uint256 cap, uint256 attempted);',
    );
  }
}

function addCometDepositWithdraw(
  c: ContractBuilder,
  opts: GenerateOptions,
  applied: FindingId[],
): void {
  const fns = defineFunctions({
    _deposit: {
      kind: 'internal',
      args: [
        { type: 'address', name: 'caller' },
        { type: 'address', name: 'receiver' },
        { type: 'uint256', name: 'assets' },
        { type: 'uint256', name: 'shares' },
      ],
      mutability: 'nonpayable',
    },
    _withdraw: {
      kind: 'internal',
      args: [
        { type: 'address', name: 'caller' },
        { type: 'address', name: 'receiver' },
        { type: 'address', name: 'owner' },
        { type: 'uint256', name: 'assets' },
        { type: 'uint256', name: 'shares' },
      ],
      mutability: 'nonpayable',
    },
    _withdrawFromComet: {
      kind: 'internal',
      args: [
        { type: 'uint256', name: 'assets' },
        { type: 'address', name: 'to' },
      ],
      returns: ['uint256'],
      mutability: 'nonpayable',
    },
  });

  const depositBody: string[] = [];
  if (opts.depositCap !== undefined) {
    depositBody.push(
      'if (_managedAssets + assets > DEPOSIT_CAP) {',
      '    revert DepositCapExceeded(DEPOSIT_CAP, _managedAssets + assets);',
      '}',
      '',
    );
  }
  depositBody.push(
    '// ERC-4626 pulls from `caller` and mints to `receiver`. AAVE-VLT-011 is not',
    '// conflating those, so the base implementation runs first, unmodified.',
    'super._deposit(caller, receiver, assets, shares);',
    '',
    'IERC20(asset()).forceApprove(address(COMET), assets);',
    '',
    '// CMPD-VLT-020 — credit what the position actually grew by. Comet stores a',
    '// principal and shows a present value; both conversions round DOWN, so the',
    '// balance after supplying `assets` can be short by a base unit. Booking the',
    '// requested figure would let _managedAssets drift above the real position.',
    'uint256 heldBefore = COMET.balanceOf(address(this));',
    'COMET.supply(asset(), assets);',
    '_managedAssets += COMET.balanceOf(address(this)) - heldBefore;',
  );
  c.setFunctionComments(
    ['/// @dev Supplies into Comet on the way in. Reverts with Paused() if the guardian has halted supply (AAVE-RISK-010).'],
    fns._deposit,
  );
  c.setFunctionBody(depositBody, fns._deposit);
  c.addOverride({ name: 'ERC4626' }, fns._deposit);
  applied.push(FINDING_IDS.COMET_PRESENT_VALUE_ROUNDING);

  c.setFunctionComments(
    ['/// @dev Pulls `assets` out of Comet to this contract, then pays `receiver` via the base implementation.'],
    fns._withdraw,
  );
  c.setFunctionBody(
    [
      '// A redeem of dust shares can round to zero assets; nothing to ask Comet for.',
      'uint256 received = assets > 0 ? _withdrawFromComet(assets, address(this)) : 0;',
      'super._withdraw(caller, receiver, owner, received, shares);',
    ],
    fns._withdraw,
  );
  c.addOverride({ name: 'ERC4626' }, fns._withdraw);

  c.setFunctionComments(
    [
      '/// @dev CMPD-VLT-019 — Comet.withdraw() has no "amount <= balance" check. Past the',
      '/// @dev supplied balance it BORROWS, and it can, because anyone may supplyTo() this',
      '/// @dev contract a collateral position. The withdraw is therefore capped at what',
      '/// @dev the position holds, and the position is asserted non-negative afterwards.',
      '/// @dev AAVE-VLT-004 — the amount received is measured, never assumed.',
    ],
    fns._withdrawFromComet,
  );
  c.setFunctionBody(
    [
      'uint256 held = COMET.balanceOf(address(this));',
      'if (assets > held) revert WithdrawExceedsPosition(assets, held);',
      '',
      'uint256 balanceBefore = IERC20(asset()).balanceOf(to);',
      'COMET.withdrawTo(to, asset(), assets);',
      'uint256 received = IERC20(asset()).balanceOf(to) - balanceBefore;',
      'if (received < assets) revert WithdrawShortfall(assets, received);',
      'if (COMET.borrowBalanceOf(address(this)) != 0) revert PositionWentNegative();',
      '',
      '// CMPD-VLT-020 — the withdraw may have shaved a base unit off the principal on',
      '// top of what was paid out; never let the book exceed the position.',
      '_managedAssets -= assets;',
      '_clampToPosition();',
      'return received;',
    ],
    fns._withdrawFromComet,
  );
  c.addConstantOrImmutableOrErrorDefinition(
    'error WithdrawExceedsPosition(uint256 requested, uint256 held);',
  );
  c.addConstantOrImmutableOrErrorDefinition(
    'error WithdrawShortfall(uint256 requested, uint256 received);',
  );
  c.addConstantOrImmutableOrErrorDefinition('error PositionWentNegative();');
  applied.push(FINDING_IDS.VAULT_WITHDRAW_RETURN_IGNORED);

  if (opts.pausable) addPausable(c, accessOf(opts), [fns._deposit]);
}

/** Comet has no base supply cap; the guardian can pause supply and withdraw independently. */
function addCometLimits(c: ContractBuilder, opts: GenerateOptions, applied: FindingId[]): void {
  addErc4626Limits(c, opts, applied, {
    depositBlocked: ['if (COMET.isSupplyPaused()) return 0;'],
    depositRoom: [],
    withdrawBlocked: ['if (COMET.isWithdrawPaused()) return 0;'],
    // Comet holds the base token itself; what it holds is what it can pay out.
    liquidity: '_min(IERC20(asset()).balanceOf(address(COMET)), COMET.balanceOf(address(this)))',
  });

  const fns = defineFunctions({
    _min: {
      kind: 'internal',
      args: [
        { type: 'uint256', name: 'a' },
        { type: 'uint256', name: 'b' },
      ],
      returns: ['uint256'],
      mutability: 'pure',
    },
  });
  c.setFunctionBody(['return a < b ? a : b;'], fns._min);
}

/** Folds accrued Comet interest into the internal figure; fees accrue and are collected separately. */
function addCometHarvest(c: ContractBuilder, opts: GenerateOptions): void {
  addYieldBooking(c, opts, {
    position: 'COMET.balanceOf(address(this))',
    // The fee leaves through the same guarded path as every other withdrawal, so it
    // is capped at the position and can never open a borrow (CMPD-VLT-019).
    payFee: ['_managedAssets += fee;', 'uint256 paid = _withdrawFromComet(fee, feeRecipient);'],
    notes: [
      '/// @dev balanceOf() computes a fresh index, so this is not a stale read. Reading it',
      '/// @dev HERE is safe: a donation is credited to all holders rather than moving the',
      '/// @dev price against the next depositor, and the decimals offset covers the',
      '/// @dev empty-vault case.',
    ],
  });
}

function addCometSurface(c: ContractBuilder, opts: GenerateOptions, applied: FindingId[]): void {
  if (opts.sweepEscapeHatch) {
    const fns = defineFunctions({
      sweep: {
        kind: 'external',
        args: [
          { type: 'address', name: 'token' },
          { type: 'address', name: 'to' },
        ],
        mutability: 'nonpayable',
      },
    });
    c.setFunctionComments(
      [
        '/// @notice AAVE-VLT-009 — recover airdrops and dust.',
        '/// @dev The principal and the Comet are excluded. Comet is itself an ERC20 whose',
        '/// @dev transfer() moves the supplied balance, so a hatch that can reach it is',
        '/// @dev the vulnerability.',
      ],
      fns.sweep,
    );
    c.setFunctionBody(
      [
        'if (token == asset() || token == address(COMET)) revert CannotSweepPrincipal(token);',
        '',
        'uint256 balance = IERC20(token).balanceOf(address(this));',
        'IERC20(token).safeTransfer(to, balance);',
        'emit Swept(token, to, balance);',
      ],
      fns.sweep,
    );
    c.addConstantOrImmutableOrErrorDefinition('error CannotSweepPrincipal(address token);');
    c.addConstantOrImmutableOrErrorDefinition(
      'event Swept(address indexed token, address indexed to, uint256 amount);',
    );
    requireAccessControl(c, fns.sweep, accessOf(opts), 'SWEEPER', undefined);
    applied.push(FINDING_IDS.VAULT_NO_ESCAPE_HATCH);
  }

  if (opts.claimRewards) {
    const fns = defineFunctions({
      claimRewards: {
        kind: 'external',
        args: [{ type: 'address', name: 'to' }],
        mutability: 'nonpayable',
      },
    });
    c.setFunctionComments(
      [
        '/// @notice CMPD-VLT-021 — COMP accrues to this contract\'s Comet account and can',
        '/// @notice only be claimed to a third party by the account itself. Without this',
        '/// @notice path the rewards are stranded.',
        '/// @dev claimTo() checks hasPermission(src, msg.sender); src == msg.sender passes.',
      ],
      fns.claimRewards,
    );
    c.setFunctionBody(
      ['ICometRewards(REWARDS).claimTo(address(COMET), address(this), to, true);'],
      fns.claimRewards,
    );
    c.addConstructorArgument({ type: 'address', name: 'rewards_' });
    c.addConstantOrImmutableOrErrorDefinition('address public immutable REWARDS;');
    c.addConstructorCode('REWARDS = rewards_;');
    requireAccessControl(c, fns.claimRewards, accessOf(opts), 'HARVESTER', undefined);
    applied.push(FINDING_IDS.COMET_REWARDS_UNCLAIMABLE);
  }
}
