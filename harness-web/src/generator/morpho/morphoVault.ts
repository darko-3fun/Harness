/**
 * ERC-4626 vault over Morpho Blue.
 *
 * Morpho's integration surface differs from Aave's in three ways that each have
 * their own finding, so this is not the Aave vault with a different address:
 *
 *   MRPH-VLT-016  supply/withdraw take BOTH `assets` and `shares`, and exactly
 *                 one must be zero. Passing both, or neither, reverts with
 *                 "inconsistent input" — verified in Morpho's ErrorsLib.
 *   MRPH-CB-017   a non-empty `data` argument makes Morpho call back into this
 *                 contract. We pass empty bytes and implement no callback, so
 *                 the surface does not exist.
 *   MRPH-MKT-018  a market is identified by the hash of its parameters. Taking
 *                 them per-call lets a caller point the vault at a market with a
 *                 different oracle or LLTV; pinning them at construction doesn't.
 */

function validate(opts: GenerateOptions): void {
  const messages: ValidationMessages = {};
  validateCommon(opts, messages);
  validateVaultSettings(opts, messages);
  if (opts.morphoMarketId !== undefined && !BYTES32_RE.test(opts.morphoMarketId)) {
    messages.morphoMarketId = 'Must be a 32-byte market id';
  }
  // The contract itself takes the market as constructor arguments and works for
  // any market. The tests and the deploy script, however, have to pin a real one,
  // and there is no registry to resolve it from — so an asset with no catalogued
  // market is refused here, where the message reaches the user, rather than in
  // the test assembler.
  if (!messages.asset && !resolveMorphoMarket(opts.asset, opts.morphoMarketId)) {
    messages.asset = opts.morphoMarketId
      ? 'That market id is not one of the catalogued Morpho Blue markets for this asset'
      : 'No catalogued Morpho Blue market lends this asset. Pick USDC, USDT, WETH or DAI.';
  }
  throwIfInvalid(messages);
}

export function buildMorphoVault(opts: GenerateOptions): {
  contract: ContractBuilder;
  appliedFindingIds: FindingId[];
} {
  validate(opts);

  const applied: FindingId[] = [];
  const c = new ContractBuilder(opts.name);
  c.license = 'MIT';

  c.addParent(imp('ERC4626', IMPORT_PATHS.ERC4626), [{ lit: 'asset_' }]);
  c.addConstructionOnly(imp('ERC20', IMPORT_PATHS.ERC20), [
    { lit: `"${opts.name}"` },
    { lit: `"m${opts.name.slice(0, 10).toUpperCase()}"` },
  ]);
  c.addImportOnly(imp('IMorpho', IMPORT_PATHS.MORPHO));
  c.addImportOnly(imp('MarketParams', IMPORT_PATHS.MORPHO));
  c.addImportOnly(imp('MorphoBalancesLib', IMPORT_PATHS.MORPHO_BALANCES_LIB));
  c.addImportOnly(imp('IERC20', IMPORT_PATHS.IERC20));

  c.addLibrary(imp('SafeERC20', IMPORT_PATHS.SAFE_ERC20), ['IERC20']);
  applied.push(FINDING_IDS.UNCHECKED_EXTERNAL_CALL);

  c.addNatspecTag('title', opts.name);
  c.addNatspecTag(
    'notice',
    'ERC-4626 vault over Morpho Blue generated by HARNESS. Market parameters are pinned at construction and Morpho is never given a callback.',
  );

  addMorphoConstructor(c, opts, applied);
  addMorphoAccounting(c, opts, applied);
  addMorphoDepositWithdraw(c, opts, applied);
  addMorphoLimits(c, opts, applied);
  addMorphoHarvest(c, opts);
  addMorphoSurface(c, opts, applied);

  return { contract: c, appliedFindingIds: applied };
}

export function printMorphoVault(opts: GenerateOptions): string {
  const { contract } = buildMorphoVault(opts);
  return print(contract, [LIBS.morpho]);
}

