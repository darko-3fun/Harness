import {
  ContractBuilder,
  defineFunctions,
  requireAccessControl,
  setAccessControl,
  addPausable,
} from '@openzeppelin/wizard';

import {
  LIBS,
  accessOf,
  imp,
  print,
  throwIfInvalid,
  validateCommon,
  validateVaultSettings,
  type ValidationMessages,
} from '@/generator/shared';
import { addYieldBooking } from '@/generator/vaults/harvest';
import { addErc4626Limits } from '@/generator/vaults/limits';
import { FINDING_IDS, IMPORT_PATHS, type FindingId, type GenerateOptions } from '@/types';

function validate(opts: GenerateOptions): void {
  const messages: ValidationMessages = {};
  validateCommon(opts, messages);
  validateVaultSettings(opts, messages);
  throwIfInvalid(messages);
}

export function buildErc4626Vault(opts: GenerateOptions): {
  contract: ContractBuilder;
  appliedFindingIds: FindingId[];
} {
  validate(opts);

  const applied: FindingId[] = [];
  const c = new ContractBuilder(opts.name);
  c.license = 'MIT';

  // ERC4626 already inherits ERC20, so only ERC4626 goes in the inheritance list;
  // ERC20's constructor is still reachable and needs the name/symbol.
  c.addParent(imp('ERC4626', IMPORT_PATHS.ERC4626), [{ lit: 'asset_' }]);
  c.addConstructionOnly(imp('ERC20', IMPORT_PATHS.ERC20), [
    { lit: `"${opts.name}"` },
    { lit: `"h${opts.name.slice(0, 10).toUpperCase()}"` },
  ]);
  c.addImportOnly(imp('IPool', IMPORT_PATHS.POOL));
  c.addImportOnly(imp('IPoolAddressesProvider', IMPORT_PATHS.POOL_ADDRESSES_PROVIDER));
  c.addImportOnly(imp('IERC20', IMPORT_PATHS.IERC20));

  c.addLibrary(imp('SafeERC20', IMPORT_PATHS.SAFE_ERC20), ['IERC20']);
  applied.push(FINDING_IDS.UNCHECKED_EXTERNAL_CALL);

  c.addNatspecTag('title', opts.name);
  c.addNatspecTag(
    'notice',
    'ERC-4626 vault over Aave v3 generated by HARNESS. Share price is derived from internal accounting, never from a freely transferable aToken balance.',
  );

  addVaultConstructor(c, opts);
  addAccounting(c, opts, applied);
  addDepositWithdraw(c, opts, applied);
  addLimits(c, opts, applied);
  addHarvest(c, opts, applied);
  addVaultSurface(c, opts, applied);

  return { contract: c, appliedFindingIds: applied };
}

export function printErc4626Vault(opts: GenerateOptions): string {
  const { contract } = buildErc4626Vault(opts);
  return print(contract, [LIBS.aave, LIBS.aavePeriphery]);
}

